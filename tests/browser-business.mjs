import {chromium} from "playwright";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {readFile} from "node:fs/promises";
const browser=await chromium.launch({channel:"chrome",headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:1320,height:850},acceptDownloads:true});
const errors=[];
page.on("pageerror",err=>errors.push(err.message));
try{
  const response=await page.goto("http://127.0.0.1:8765/business.html",{waitUntil:"domcontentloaded"});
  assert.equal(response.status(),200);
  await page.waitForFunction(()=>document.querySelector("#business-area").textContent.trim()!=="—");
  assert.match(await page.locator("#business-latest").textContent(),/2026-09/);
  assert.match(await page.locator("#business-provenance").textContent(),/Sentinel-2/);
  assert.equal(await page.locator("#business-print").isEnabled(),true);
  const [initial]=await Promise.all([page.waitForEvent("download"),page.locator("#business-json").click()]);
  const initialReport=JSON.parse(await readFile(await initial.path(),"utf8"));
  assert.equal(initialReport.summary.records,36);
  assert.equal(initialReport.researchOnly,true);
  assert.equal(initialReport.provenance.officialWetlandBoundary,false);
  assert.equal(initialReport.sourceKind,"bundled_historical");
  await page.locator("#business-from").selectOption("2024-06");
  await page.locator("#business-to").selectOption("2025-07");
  assert.match(await page.locator("#business-flag-list").textContent(),/2024-07/);
  assert.match(await page.locator("#business-flag-list").textContent(),/2025-03/);
  const [csv]=await Promise.all([page.waitForEvent("download"),page.locator("#business-csv").click()]);
  const csvText=await readFile(await csv.path(),"utf8");
  assert.match(csvText,/matched_pixel_change_km2/);
  assert.ok(csvText.includes("2024-06"));
  assert.ok(!csvText.includes("2023-10"));
  await page.locator("#business-from").selectOption("2026-09");
  await page.locator("#business-to").selectOption("2025-01");
  assert.match(await page.locator("#business-status").textContent(),/تعذر إعداد التقرير/);
  assert.equal(await page.locator("#business-json").isDisabled(),true);
  await page.locator("#business-reset").click();
  assert.equal(await page.locator("#business-json").isEnabled(),true);
  const fixture=JSON.parse(readFileSync("data/hawizeh-actual-observations.json","utf8"));
  fixture.imagery="Synthetic browser fixture — not operational imagery";
  fixture.source_workflow="javascript:alert(1)";
  await page.locator("#business-upload").setInputFiles({name:"test-unverified.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(fixture))});
  assert.match(await page.locator("#business-source-tag").textContent(),/مستورد/);
  assert.equal(await page.locator("#business-evidence").isHidden(),true,"untrusted source URL must not be linked");
  assert.match(await page.locator("#business-share-warning").textContent(),/لا يتضمن ملفك/);
  const [external]=await Promise.all([page.waitForEvent("download"),page.locator("#business-json").click()]);
  const externalReport=JSON.parse(await readFile(await external.path(),"utf8"));
  assert.equal(externalReport.sourceKind,"user_supplied_unverified");
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator("#business-report").isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log("Business workspace: historical load, reviews, export, fail-closed interval, upload, safety, mobile OK");
}finally{
 await browser.close();
}
